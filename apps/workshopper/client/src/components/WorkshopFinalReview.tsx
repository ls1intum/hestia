import React, { useState } from "react";
import { saveAs } from "file-saver";
import { LearningGoalPlan, WorkshopSession, WorkshopInput, SlideData } from "@/lib/workshop-generator";
import { Card } from "@/components/ui/card";
import { Clock, Target, ArrowLeft, Download, CheckCircle2, ChevronDown, Users } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Accordion, AccordionContent, AccordionItem, AccordionTrigger } from "@/components/ui/accordion";
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from "@/components/ui/tooltip";
import { toast } from "@/hooks/use-toast";
import { assemblePptx, exportPdf, exportPptx, errorMessage, handleAuthError, downloadName } from "@/lib/api";
import { getMechanicDescription, MODE_COLORS } from "@/lib/constants";
import { phaseInfo } from "@/lib/phases";
import { blockContent, blockMethods } from "@/lib/block-content";
import { BlockDetails } from "./timetable/BlockDetails";
import { UnderstandingCheckSteps } from "./timetable/UnderstandingCheckSteps";

// Removed duplicate local declarations

interface Props {
  session: WorkshopSession;
  goals?: LearningGoalPlan[];
  meta: WorkshopInput;
  slidesCache: Record<number, SlideData[]>;
  onBack: () => void;
  onDone: () => void;
}

const fmtTime = (m: number) => {
  const h = Math.floor(m / 60);
  const mm = (m % 60).toString().padStart(2, "0");
  return `${h.toString().padStart(2, "0")}:${mm}`;
};

export default function WorkshopFinalReview({ session, goals = [], meta, slidesCache, onBack, onDone }: Props) {
  const [isExporting, setIsExporting] = useState(false);

  const totalDuration = session.blocks.reduce((s, b) => s + (b.duration || 0), 0);

  // Compute running start times
  let cursor = 0;
  const rows = session.blocks.map((block) => {
    const start = cursor;
    cursor += block.duration;
    return { block, start: fmtTime(start), end: fmtTime(cursor) };
  });

  const downloadDeck = async () => {
    setIsExporting(true);
    toast({ title: "Preparing Deck…", description: "Combining cached slides and generating any missing ones." });
    try {
      const allCachedSlides = session.blocks.flatMap((_, i) => slidesCache[i] ?? []);
      const hasAllCached = session.blocks.every((_, i) => !!slidesCache[i]);

      const blob = hasAllCached && allCachedSlides.length > 0
        ? await assemblePptx(session, meta, allCachedSlides)
        : await exportPptx(session, meta, goals);
      saveAs(blob, downloadName.slides(session.title));
      toast({ title: "Slides Downloaded", description: hasAllCached ? "Assembled from cache (fast!)." : "Generated by AI." });
    } catch (e) {
      if (!handleAuthError(e)) toast({ title: "Download failed", description: errorMessage(e, "The export failed."), variant: "destructive" });
    } finally {
      setIsExporting(false);
    }
  };

  const downloadPdf = async () => {
    setIsExporting(true);
    toast({ title: "Generating PDF…" });
    try {
      saveAs(await exportPdf(session, meta, goals), downloadName.timetable(session.title));
      toast({ title: "PDF downloaded" });
    } catch (e) {
      if (!handleAuthError(e)) toast({ title: "Download failed", description: errorMessage(e, "The export failed."), variant: "destructive" });
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <div className="space-y-6 pb-20">
      <Card className="border-border/60 shadow-lg bg-surface flex flex-col max-w-5xl mx-auto w-full">
        {/* Header Block */}
        <div className="p-6 pb-2">
          <div className="font-display font-bold text-3xl mb-2 flex items-center justify-between gap-4">
            <span>{session.title || "Workshop Session Plan"}</span>
          </div>
          <div className="flex items-center gap-x-6 gap-y-2 flex-wrap text-sm text-muted-foreground font-body">
            <span className="flex items-center gap-1.5 font-medium"><Clock className="h-4 w-4 text-primary/60" /> {meta.duration || totalDuration} min</span>
            <span className="flex items-center gap-1.5 font-medium"><Users className="h-4 w-4 text-primary/60" /> {meta.participants} participants{session.studentBackground ? `, ${session.studentBackground}` : ""}</span>
          </div>

          <div className="mt-5 space-y-4">
            <div>
              <h3 className="font-body font-semibold flex items-center gap-2 mb-1"><Target className="h-4 w-4 text-primary" /> Learning Goals</h3>
              <ul className="text-sm font-body text-foreground/80 flex flex-col gap-1.5 list-none">
                {goals?.map((g, idx) => (
                  <li key={idx} className="flex items-start gap-1.5">
                    <span className="text-primary/60 mt-0.5">•</span>
                    <span className="leading-snug">{g.goal}</span>
                  </li>
                ))}
              </ul>
            </div>

          </div>
        </div>

        {/* Timetable */}
        <div className="flex-1 px-2 sm:px-6 py-6 pb-8">
          <div className="mx-auto max-w-4xl">

            <div className="relative mt-2">
              <Accordion type="multiple" className="flex flex-col">
                {rows.map(({ block }, i) => {
                  const phase = phaseInfo(block.phase);
                  const mode = phase.mode;
                  const modeColors = MODE_COLORS[mode];
                  const isBreak = mode === "break";

                  const nextBlock = i < rows.length - 1 ? rows[i + 1].block : null;
                  // Gap below this block encodes its duration on the timeline
                  const gapBelow = i < rows.length - 1 ? Math.max(12, block.duration * 5) : 0;

                  const nextIsSmall = nextBlock && phaseInfo(nextBlock.phase).compact;
                  const nextDot = nextIsSmall ? 18 : 26;

                  const tagsContent = (() => {
                    const allMethods = blockMethods(block);

                    if (allMethods.length === 0) return null;

                    return (
                      <div className="flex items-center flex-wrap gap-1.5 shrink-0 ml-2">
                        <div className="h-4 w-[1px] bg-border/60 mx-1 shrink-0 hidden sm:block"></div>
                        {allMethods.map((m, j) => (
                          <TooltipProvider key={`meth-${j}`}>
                            <Tooltip>
                              <TooltipTrigger asChild>
                                <div
                                  style={{ backgroundColor: modeColors.badgeBg, color: modeColors.badgeText }}
                                  className="inline-flex items-center justify-center whitespace-nowrap rounded-full h-5 px-2.5 text-[0.75rem] font-semibold shrink-0 cursor-help"
                                >
                                  {m}
                                </div>
                              </TooltipTrigger>
                              <TooltipContent side="top" className="max-w-[250px] text-xs font-body font-normal">
                                {getMechanicDescription(m)}
                              </TooltipContent>
                            </Tooltip>
                          </TooltipProvider>
                        ))}
                      </div>
                    );
                  })();

                  const innerContent = (
                    <div className="relative flex items-center w-full text-left">
                      {/* Time label column: 3.5rem (w-14) */}
                      <div className="w-14 shrink-0 flex flex-col justify-center text-right hidden sm:flex font-mono text-sm pr-2"
                        style={{ color: block.duration >= 10 ? 'var(--hestia-primary)' : 'var(--hestia-text-muted)', fontWeight: block.duration >= 10 ? 700 : 400 }}>
                        {block.duration}m
                      </div>

                      {/* Spine column: 2rem (w-8) */}
                      <div className="w-8 shrink-0 flex flex-col justify-center items-center relative hidden sm:flex self-stretch">
                        {/* Dot */}
                        <div className="absolute top-1/2 -translate-y-1/2 w-3 h-3 rounded-full shadow-sm z-10"
                          style={{ backgroundColor: modeColors.dot, border: '1px solid white' }} />
                      </div>

                      {/* The block — fixed height, gap below encodes duration */}
                      <div
                        className={`transition-all rounded-xl ${phase.compact ? "px-3" : "px-4"} flex items-center flex-wrap gap-2 shrink-0`}
                        style={{
                          minHeight: phase.compact ? "36px" : "44px",
                          backgroundColor: modeColors.bgTint,
                          border: isBreak ? `1.5px dashed ${modeColors.border}` : `1px solid rgba(0,0,0,0.08)`,
                          boxShadow: isBreak ? "none" : "0 1px 4px rgba(0,0,0,0.07)",
                        }}
                      >
                        <span className="text-base shrink-0">{phase.emoji}</span>
                        <span className="font-body text-sm font-medium text-foreground whitespace-nowrap">{block.phaseLabel}</span>
                        {tagsContent}
                        {phase.expandable && <ChevronDown className="h-4 w-4 text-muted-foreground transition-transform duration-200 shrink-0 hidden sm:block ml-1" />}
                      </div>
                    </div>
                  );

                  if (!phase.expandable) {
                    return (
                      <div
                        key={block.blockId || i}
                        className="border-0 relative bg-transparent mb-[var(--gap-below)]"
                        style={{ '--gap-below': `${gapBelow}px` } as React.CSSProperties}
                      >
                        {/* Timeline spine for blocks without details (break, buffer) */}
                        {i < rows.length - 1 && (
                          <div
                            className="absolute w-[2px] z-0 opacity-60 hidden sm:block transition-all duration-300"
                            style={{
                              backgroundColor: modeColors.dot,
                              top: '18px',
                              left: '71px',
                              bottom: `calc(-1 * (var(--gap-below) + ${nextDot}px))`
                            }}
                          />
                        )}
                        {innerContent}
                      </div>
                    );
                  }

                  return (
                    <AccordionItem
                      key={block.blockId || i}
                      value={`item-${block.blockId || i}`}
                      className="border-0 relative bg-transparent group/item transition-all duration-300 data-[state=closed]:mb-[var(--gap-below)] data-[state=open]:mb-6"
                      style={{
                        '--gap-below': `${gapBelow}px`,
                        '--closed-bottom': `calc(-1 * (var(--gap-below) + ${nextDot}px))`,
                        '--open-bottom': `calc(-1 * (24px + ${nextDot}px))`
                      } as React.CSSProperties}
                    >
                      {/* Timeline spine */}
                      {i < rows.length - 1 && (
                        <div
                          className="absolute w-[2px] z-0 opacity-60 hidden sm:block transition-all duration-300 group-data-[state=closed]/item:bottom-[var(--closed-bottom)] group-data-[state=open]/item:bottom-[var(--open-bottom)]"
                          style={{
                            backgroundColor: modeColors.dot,
                            top: '26px',
                            left: '71px'
                          }}
                        />
                      )}
                      <AccordionTrigger className="w-full py-1 hover:no-underline [&>svg]:hidden group focus:outline-none">
                        {innerContent}
                      </AccordionTrigger>
                      <AccordionContent className="pl-0 sm:pl-[5.5rem] pr-0 pb-4 pt-2 relative z-10">
                        {(() => {
                          const content = blockContent(block, goals.map(g => g.goal).filter(Boolean));
                          if (content.kind === "evaluate") {
                            return (
                              <div className="mt-2">
                                <UnderstandingCheckSteps
                                  allSteps={content.steps}
                                  renderEditable={(_, text, className) => <span className={className}>{text}</span>}
                                  mappings={meta.evaluateMappings}
                                  goalIds={goals.map(g => g.id)}
                                />
                              </div>
                            );
                          }
                          if (content.kind === "other") {
                            return (
                              <div className="pl-4 mt-2">
                                <p className="text-sm text-muted-foreground leading-relaxed">{block.objective || block.description}</p>
                              </div>
                            );
                          }
                          return (
                            <BlockDetails
                              content={content}
                              methods={blockMethods(block)}
                              renderText={(item, className) => <span className={className}>{item.text}</span>}
                              className="pl-4 mt-2"
                            />
                          );
                        })()}
                      </AccordionContent>
                    </AccordionItem>
                  );
                })}
              </Accordion>
            </div>
          </div>
        </div>

        {/* Sticky Footer Bar */}
        <div className="sticky bottom-4 z-30 mx-4 mb-4 rounded-xl border border-border/80 bg-surface backdrop-blur-md shadow-2xl p-3 flex items-center justify-between gap-4 mt-6 transition-all">
          <Button
            variant="outline"
            size="sm"
            onClick={onBack}
            className="gap-2 font-body shrink-0 bg-transparent border-[1.5px] border-primary text-primary hover:bg-primary/5 transition-all duration-150"
          >
            <ArrowLeft className="h-4 w-4" /> Previous
          </Button>

          <div className="flex items-center gap-2 flex-wrap justify-end">
            <Button size="sm" variant="outline" onClick={downloadPdf} disabled={isExporting} className="gap-2 transition-all duration-150">
              <Download className="h-3.5 w-3.5" /> PDF Timetable
            </Button>
            <Button size="sm" variant="outline" onClick={downloadDeck} disabled={isExporting} className="gap-2 transition-all duration-150">
              <Download className="h-3.5 w-3.5" /> PPTX Slides
            </Button>
            <Button
              size="sm"
              onClick={onDone}
              className="gap-2 shadow-md hover:shadow-lg bg-primary text-primary-foreground font-semibold shrink-0 rounded-lg transition-all duration-150"
            >
              <CheckCircle2 className="h-3.5 w-3.5" /> Done
            </Button>
          </div>
        </div>
      </Card>
    </div>
  );
}
